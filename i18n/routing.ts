// ============================================================================
// 语言路由定义（next-intl 的核心配置）
// ----------------------------------------------------------------------------
// defineRouting 告诉 next-intl：支持哪些语言、默认语言是什么。
// 中间件和导航 API 都引用它，做到“一处定义、处处复用”。
// ============================================================================
import { defineRouting } from 'next-intl/routing';

export const routing = defineRouting({
  // 支持的语言列表
  locales: ['zh', 'en'],
  // 默认语言：访问 / 时按此重定向（例如 → /zh）
  defaultLocale: 'zh',
});
